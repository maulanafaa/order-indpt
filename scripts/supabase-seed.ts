/**
 * Writes supabase/seed.sql from src/data: stores, hours, services, menu,
 * availability and promos. Run with `npm run db:seed-sql`, then run the SQL in
 * the Supabase SQL editor (it replaces the catalog rows; user data is untouched).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import type { z } from 'zod'
import { dataFiles } from '../src/data/schema'

type Files = typeof dataFiles
const load = <K extends keyof Files>(file: K): z.infer<Files[K]> =>
  (dataFiles[file] as z.ZodType).parse(JSON.parse(readFileSync(new URL(`../src/data/${file}`, import.meta.url), 'utf8'))) as z.infer<Files[K]>

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (Array.isArray(v)) return `array[${v.map(q).join(',')}]::text[]`
  return `'${String(v).replace(/'/g, "''")}'`
}

const insert = (table: string, cols: string[], rows: unknown[][]) =>
  rows.length ? `insert into public.${table} (${cols.join(', ')}) values\n${rows.map((r) => `  (${r.map(q).join(', ')})`).join(',\n')};\n` : ''

const stores = load('stores.json')
const hours = load('storeHours.json')
const services = load('storeServices.json')
const categories = load('categories.json')
const items = load('items.json')
const groups = load('modifierGroups.json')
const modifiers = load('modifiers.json')
const availability = load('storeAvailability.json')
const promos = load('promos.json')

// Order inside an item / group follows the JSON order.
const groupOrder = new Map<string, number>()
const modOrder = new Map<string, number>()
const counter = new Map<string, number>()
for (const g of groups) {
  const n = counter.get(g.itemId) ?? 0
  groupOrder.set(g.id, n)
  counter.set(g.itemId, n + 1)
}
for (const m of modifiers) {
  const n = counter.get(m.groupId) ?? 0
  modOrder.set(m.id, n)
  counter.set(m.groupId, n + 1)
}

const sql = `-- Generated by scripts/supabase-seed.ts from src/data. Do not edit by hand.
begin;
-- Columns added after the first schema.
alter table public.items add column if not exists is_new boolean not null default false;
delete from public.store_availability;
delete from public.promos;
delete from public.modifiers;
delete from public.modifier_groups;
delete from public.items;
delete from public.categories;
delete from public.store_services;
delete from public.store_hours;
-- Stores can be referenced by orders and profiles: upsert instead of delete.
${insert('stores', ['id', 'slug', 'name', 'address', 'country', 'lat', 'lng', 'phone', 'email', 'cover_image'], stores.map((s) => [s.id, s.slug, s.name, s.address, s.country, s.lat, s.lng, s.phone, s.email, s.coverImage])).replace(/;\n$/, `
on conflict (id) do update set slug = excluded.slug, name = excluded.name, address = excluded.address, country = excluded.country,
  lat = excluded.lat, lng = excluded.lng, phone = excluded.phone, email = excluded.email, cover_image = excluded.cover_image;
`)}${insert('store_hours', ['store_id', 'day', 'opens', 'closes'], hours.map((h) => [h.storeId, h.day, h.opens, h.closes]))}${insert('store_services', ['store_id', 'method', 'supported', 'available_now'], services.map((s) => [s.storeId, s.method, s.supported, s.availableNow]))}${insert('categories', ['id', 'name', 'sort_order'], categories.map((c) => [c.id, c.name, c.sortOrder]))}${insert('items', ['id', 'slug', 'category_id', 'name', 'description', 'price', 'calories', 'is_best_seller', 'is_new', 'allergens'], items.map((i) => [i.id, i.slug, i.categoryId, i.name, i.description, i.price, i.calories, i.isBestSeller, i.isNew, i.allergens]))}${insert('modifier_groups', ['id', 'item_id', 'name', 'type', 'min', 'max', 'required', 'sort_order'], groups.map((g) => [g.id, g.itemId, g.name, g.type, g.min, g.max, g.required, groupOrder.get(g.id)]))}${insert('modifiers', ['id', 'group_id', 'name', 'price', 'max_qty', 'sort_order'], modifiers.map((m) => [m.id, m.groupId, m.name, m.price, m.maxQty, modOrder.get(m.id)]))}${insert('store_availability', ['store_id', 'item_id', 'modifier_id', 'available', 'reason'], availability.map((a) => [a.storeId, a.itemId ?? null, a.modifierId ?? null, a.available, a.reason ?? null]))}${insert('promos', ['code', 'title', 'type', 'value', 'max_discount', 'min_order', 'valid_from', 'valid_until', 'methods', 'free_item_id', 'requires_category_id', 'once_per_customer'], promos.map((p) => [p.code, p.title, p.type, p.value, p.maxDiscount, p.minOrder, p.validFrom, p.validUntil, p.methods, p.freeItemId ?? null, p.requiresCategoryId ?? null, p.oncePerCustomer ?? false]))}commit;
`

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`supabase/seed.sql: ${stores.length} stores, ${items.length} items, ${modifiers.length} add-ons, ${promos.length} promos`)
